import { readdir, readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { join } from "node:path";
import { parse, type INode } from "svgson";
import { deriveRig, type Rig, type RawNode } from "./rigs";
import candidates from "./popular.candidates.json" with { type: "json" };

const SRC = "node_modules/@tabler/icons/icons/outline";
const OUT = "src/icons";
const TAGS = new Set(["path", "circle", "rect", "line", "polyline", "polygon", "ellipse"]);

const pascal = (s: string) =>
  s.split("-").map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");

function toNodes(root: INode): RawNode[] {
  return root.children
    .filter((c) => TAGS.has(c.name))
    // first path is the 24x24 bounding box tabler ships in every icon
    .filter((c) => !(c.name === "path" && c.attributes.stroke === "none"))
    .map((c) => [c.name, c.attributes] as const);
}

const overrides = new Set(
  (await readdir("src/overrides").catch(() => [])).map((f) => f.replace(/\.tsx$/, "")),
);
/** The everyday icons, listed first in the gallery. */
const popular = [...overrides, ...(candidates as string[]).filter((n) => !overrides.has(n))];

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const files = (await readdir(SRC)).filter((f) => f.endsWith(".svg"));
const index: string[] = [];
const manifest: { name: string; component: string; override: boolean }[] = [];
const meta: Record<string, { category: string; tags: string[] }> = JSON.parse(
  await readFile("node_modules/@tabler/icons/icons.json", "utf8"),
);
const data: Record<string, [Rig[], unknown, string, string]> = {};
let broken = 0;

for (const file of files) {
  const name = file.replace(/\.svg$/, "");
  const nodes = toNodes(await parse(await readFile(join(SRC, file), "utf8")));
  if (!nodes.length) continue;
  const category = meta[name]?.category ?? "Other";
  let rig: Rig[];
  try {
    rig = deriveRig(name, category, nodes);
  } catch (e) {
    broken++;
    console.warn(`rig failed for ${name}: ${(e as Error).message}`);
    rig = [{ fx: "pop", n: nodes.map((_, i) => i), a: 0.1 }];
  }
  if (!rig.length) rig = [{ fx: "pop", n: nodes.map((_, i) => i), a: 0.1 }];
  const component = `${pascal(name)}Icon`;
  const hasOverride = overrides.has(name);

  const body = `"use client";

import { forwardRef } from "react";
import { AnimatedIconBase, type AnimatedIconHandle, type AnimatedIconProps, type IconNode, type Rig } from "@/lib/animated-icon";

const nodes: IconNode[] = ${JSON.stringify(nodes)};
const rig: Rig[] = ${JSON.stringify(rig)};

export const ${component} = forwardRef<AnimatedIconHandle, AnimatedIconProps>((props, ref) => (
  <AnimatedIconBase ref={ref} nodes={nodes} rig={rig} {...props} />
));
${component}.displayName = "${component}";
`;
  await writeFile(join(OUT, `${name}.tsx`), body);
  index.push(
    hasOverride
      ? `export { ${component} } from "../overrides/${name}";`
      : `export { ${component} } from "./${name}";`,
  );
  manifest.push({ name, component, override: hasOverride });
  data[name] = [rig, nodes, category, (meta[name]?.tags ?? []).join(" ").toLowerCase()];
}

await writeFile(join(OUT, "index.ts"), index.join("\n") + "\n");
await writeFile(join(OUT, "manifest.json"), JSON.stringify(manifest));
const ov = manifest.filter((m) => m.override);
await writeFile(
  "apps/web/components/overrides-map.ts",
  `// generated by scripts/generate.ts
import type { ForwardRefExoticComponent, RefAttributes } from "react";
import type { AnimatedIconHandle, AnimatedIconProps } from "@lib/animated-icon";
${ov.map((m) => `import { ${m.component} } from "@overrides/${m.name}";`).join("\n")}

type Override = ForwardRefExoticComponent<AnimatedIconProps & RefAttributes<AnimatedIconHandle>>;
export const TOTAL = ${manifest.length};
/** Everyday icons, listed first in the gallery. */
export const POPULAR: string[] = ${JSON.stringify(popular.filter((n) => data[n]))};
export const overrides: Record<string, Override> = {
${ov.map((m) => `  "${m.name}": ${m.component},`).join("\n")}
};
`,
);
await mkdir("apps/web/public", { recursive: true });
await writeFile("apps/web/public/icons-data.json", JSON.stringify(data));
console.log(`generated ${manifest.length} icons (${overrides.size} hand-written, ${popular.filter((n) => data[n]).length} popular, ${broken} fallbacks)`);
